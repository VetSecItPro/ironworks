import { useQuery } from "@tanstack/react-query";
import { Edit2 } from "lucide-react";
import { useState } from "react";
import { Button } from "@/components/ui/button";
import { ScrollArea } from "@/components/ui/scroll-area";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { type KnowledgePage, knowledgeApi } from "../../api/knowledge";
import { MarkdownBody } from "../MarkdownBody";
import { KnowledgePageBacklinks } from "./KnowledgePageBacklinks";
import { KnowledgePageGraph } from "./KnowledgePageGraph";
import { AutoBadge, DocTypeBadge } from "./LibraryBadges";

export function KnowledgePageViewer({
  companyId: _companyId,
  pageId,
  onEdit,
  onNavigate,
}: {
  companyId: string;
  pageId: string;
  onEdit?: (page: KnowledgePage) => void;
  onNavigate?: (pageId: string) => void;
}) {
  const [internalPageId, setInternalPageId] = useState<string | null>(null);
  const activePageId = internalPageId ?? pageId;

  const { data, isLoading, error } = useQuery({
    queryKey: ["knowledge-page", activePageId],
    queryFn: () => knowledgeApi.get(activePageId),
    enabled: !!activePageId,
  });

  const handleNavigate = (target: string) => {
    if (onNavigate) {
      onNavigate(target);
    } else {
      // Fallback: track internally so click-through still works without parent wiring.
      setInternalPageId(target);
    }
  };

  if (isLoading) {
    return (
      <div className="flex items-center justify-center h-full text-sm text-muted-foreground">Loading document...</div>
    );
  }

  if (error) {
    return (
      <div className="flex items-center justify-center h-full text-sm text-destructive">
        {error instanceof Error ? error.message : "Failed to load document"}
      </div>
    );
  }

  if (!data) return null;

  return (
    <div className="h-full flex">
      <div className="flex-1 min-w-0 flex flex-col">
        <div className="flex items-center justify-between px-4 py-2.5 border-b border-border bg-muted/20 shrink-0">
          <div className="flex items-center gap-2 min-w-0">
            <span className="text-sm font-medium truncate">{data.title}</span>
            <div className="flex items-center gap-1 shrink-0">
              {data.autoGenerated && <AutoBadge />}
              <DocTypeBadge documentType={data.documentType} />
            </div>
          </div>
          <div className="flex items-center gap-2 shrink-0">
            <span className="text-xs text-muted-foreground">
              {new Date(data.updatedAt).toLocaleDateString("en-US", {
                month: "short",
                day: "numeric",
                year: "numeric",
              })}
            </span>
            {onEdit && (
              <Button variant="ghost" size="sm" className="h-7 text-xs" onClick={() => onEdit(data)}>
                <Edit2 className="h-3 w-3 mr-1" />
                Edit
              </Button>
            )}
          </div>
        </div>
        <Tabs defaultValue="document" className="flex-1 min-h-0 flex flex-col gap-0">
          <TabsList className="mx-4 mt-2 self-start">
            <TabsTrigger value="document">Document</TabsTrigger>
            <TabsTrigger value="graph">Graph</TabsTrigger>
          </TabsList>
          <TabsContent value="document" className="flex-1 min-h-0">
            <ScrollArea className="h-full min-h-0">
              <div className="p-6 max-w-none">
                <MarkdownBody>{data.body}</MarkdownBody>
              </div>
            </ScrollArea>
          </TabsContent>
          <TabsContent value="graph" className="flex-1 min-h-0 p-4">
            <KnowledgePageGraph pageId={activePageId} onNavigate={handleNavigate} />
          </TabsContent>
        </Tabs>
      </div>
      <aside className="w-[280px] shrink-0 hidden md:flex">
        <KnowledgePageBacklinks pageId={activePageId} onNavigate={handleNavigate} />
      </aside>
    </div>
  );
}
